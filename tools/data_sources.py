"""
Write docs/DATA_SOURCES.md: every importer catalog dataset (grouped by
provider, from importer/external_catalog.py), the sources read outside the
importer and the cited regulations and literature (core/data_sources.py).

    uv run python tools/data_sources.py           # write the file
    uv run python tools/data_sources.py --check   # exit 1 when the file is out of date

core/tests/test_data_sources.py runs the same render and fails when the
committed file differs, so a new catalog entry must come with a rerun.
"""
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "DATA_SOURCES.md"


def _setup():
    sys.path.insert(0, str(ROOT))
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "DigitalTwin.settings")
    import django
    django.setup()


def _cell(text):
    return str(text or "").replace("|", "\\|").replace("\n", " ").strip()


def _endpoint(entry):
    """Where a catalog dataset comes from: URL + layer, Earth Engine asset, CBS table or KNMI dataset."""
    if entry.get("table_id"):
        return f"CBS table `{entry['table_id']}`"
    if entry.get("format") == "ogc_api" and entry.get("url"):
        return f"{entry['url']} (OGC API collection `{entry.get('collection')}`)"
    if entry.get("collection") or entry.get("asset_id"):
        return f"Earth Engine `{entry.get('collection') or entry.get('asset_id')}`"
    if entry.get("dataset_name"):
        version = f" v{entry['dataset_version']}" if entry.get("dataset_version") else ""
        return f"KNMI Data Platform `{entry['dataset_name']}`{version}"
    url = entry.get("url") or entry.get("wcs_url") or entry.get("api_base") or ""
    layer = f" (`{entry['layer']}`)" if entry.get("layer") else ""
    if entry.get("openeo_process"):
        layer = f" (openEO `{entry['openeo_process']}`)"
    if entry.get("format") == "daily" and not url:
        return "KNMI daggegevens (daily station data)"
    return f"{url}{layer}" if url else "–"


def render():
    from core.data_sources import OTHER_SOURCES, REFERENCES
    from importer.external_catalog import EXTERNAL_DATA_CATALOG, SOURCE_INFO

    lines = [
        "# Data sources",
        "",
        "Every external source CrossTwin reads, and the regulations and literature its calculations cite.",
        "Generated by `tools/data_sources.py` from `importer/external_catalog.py` and `core/data_sources.py`;",
        "do not edit by hand. Stored rows record their own source (dataset key, scene, station, year) — see",
        "*Reproducibility* in `.claude/CLAUDE.md`.",
        "",
        "## 1. Importer catalog (Retrieve Data from APIs)",
        "",
        f"{len(EXTERNAL_DATA_CATALOG)} datasets from {len({e['source'] for e in EXTERNAL_DATA_CATALOG})} providers.",
        "",
    ]
    order = list(SOURCE_INFO) + sorted({e["source"] for e in EXTERNAL_DATA_CATALOG} - set(SOURCE_INFO))
    for source in order:
        entries = [e for e in EXTERNAL_DATA_CATALOG if e["source"] == source]
        if not entries:
            continue
        info = SOURCE_INFO.get(source, {})
        auth = "authentication required" if info.get("auth_required") else "no authentication"
        lines += [
            f"### {info.get('full_name') or info.get('name') or source}",
            "",
            f"{_cell(info.get('description'))} *({auth}; source key `{source}`)*",
            "",
            "| Key | Dataset | Category | Stored in | Endpoint |",
            "|---|---|---|---|---|",
        ]
        for e in sorted(entries, key=lambda e: (e.get("category", ""), e["key"])):
            name = _cell(e.get("name"))
            if not e.get("enabled", True):
                name += " *(disabled)*"
            lines.append(f"| `{e['key']}` | {name} | {_cell(e.get('category'))} | "
                         f"`{e.get('target_model', '–')}` | {_cell(_endpoint(e))} |")
        lines.append("")

    lines += [
        "## 2. Sources read outside the importer",
        "",
        "| Source | Provider | Endpoint / asset | Used by | Notes |",
        "|---|---|---|---|---|",
    ]
    lines += [f"| {_cell(a)} | {_cell(b)} | {_cell(c)} | {_cell(d)} | {_cell(n)} |" for a, b, c, d, n in OTHER_SOURCES]
    lines += [
        "",
        "## 3. Regulations, standards and literature",
        "",
        "| Key | Reference | Used by |",
        "|---|---|---|",
    ]
    lines += [f"| {_cell(k)} | {_cell(r)} | {_cell(u)} |" for k, r, u in REFERENCES]
    lines.append("")
    return "\n".join(lines)


def main():
    _setup()
    text = render()
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is out of date: run uv run python tools/data_sources.py")
            sys.exit(1)
        print(f"{OUTPUT} is current")
        return
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
