def parse(text):
    """Nodes (id -> label, category, comment) and edges (a, b, attrs, comment), legend excluded."""
    text = re.sub(r"subgraph cluster_legend \{.*?\n    \}", "", text, flags=re.S)
    nodes, edges = {}, []
    category, comment = None, []
    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith("//"):
            comment.append(line.lstrip("/ ").strip())
            continue
        code, _, trailing = line.partition("//")
        code, trailing = code.strip(), trailing.strip()
        m = re.match(r'node \[fillcolor="(#[0-9A-Fa-f]{6})"', code)
        if m:
            category = DPSIR.get(m.group(1).upper(), category)
        elif m := re.match(r'(\w+)\s*\[label="([^"]*)"', code):
            nodes[m.group(1)] = {
                "label": m.group(2).replace("\\n", "\n").replace("\n ", "\n").strip(),
                "category": category,
                "comment": " ".join(comment + ([trailing] if trailing else [])),
            }
        elif m := re.match(r"(\w+)\s*->\s*(\w+)\s*(\[[^\]]*\])?", code):
            edges.append((m.group(1), m.group(2), m.group(3) or "", trailing))
        if code or not line:
            comment = []
    return nodes, edges


def causal_levels(nodes, edges):
    """Longest path from a source over the non-lagged edges (the graph is acyclic without them)."""
    out, indeg = defaultdict(list), {n: 0 for n in nodes}
    for a, b, attrs, _ in edges:
        if "lag" not in attrs:
            out[a].append(b)
            indeg[b] += 1
    level = {n: 0 for n in nodes}
    queue = [n for n, d in indeg.items() if d == 0]
    while queue:
        n = queue.pop()
        for m in out[n]:
            level[m] = max(level[m], level[n] + 1)
            indeg[m] -= 1
            if indeg[m] == 0:
                queue.append(m)
    return level


def build():
    nodes, edges = parse(DAG_PATH.read_text(encoding="utf-8"))
    seen, unique = set(), []
    for e in edges:  # Total_Water_Prod -> OPEX is listed twice
        if (e[0], e[1]) not in seen:
            seen.add((e[0], e[1]))
            unique.append(e)
    missing = sorted(seen - set(EDGE_STATUS))
    extra = sorted(set(EDGE_STATUS) - seen)
    if missing or extra:
        sys.exit(f"core/dag_status.py out of sync with DAG.dot\n  no status: {missing}\n  not in DAG: {extra}")

    levels = causal_levels(nodes, unique)
    degree = defaultdict(int)
    for a, b, *_ in unique:
        degree[a] += 1
        degree[b] += 1
    node_data = [{
        "id": n, "label": d["label"], "category": d["category"],
        "sector": NODE_SECTOR.get(n, "other"), "comment": d["comment"],
        "level": levels[n], "degree": degree[n],
    } for n, d in nodes.items()]
    edge_data = []
    for a, b, attrs, trailing in unique:
        status, where, note = EDGE_STATUS[(a, b)]
        edge_data.append({"id": f"{a}->{b}", "from": a, "to": b, "status": status,
                          "where": where, "note": note, "comment": trailing})
    return node_data, edge_data


def render(node_data, edge_data):
    counts = defaultdict(int)
    for e in edge_data:
        counts[e["status"]] += 1
    payload = json.dumps({
        "nodes": node_data, "edges": edge_data,
        "dpsirColors": DPSIR_COLORS, "statusColors": STATUS_COLORS,
    }, ensure_ascii=False)
    html = TEMPLATE.replace("/*DATA*/", payload)
    summary = " · ".join(f"{counts[s]} {s}" for s in STATUS_COLORS if counts[s])
    return html.replace("<!--SUMMARY-->", escape(f"{len(node_data)} nodes · {len(edge_data)} edges · {summary}"))


