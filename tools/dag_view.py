# fillcolor of each `node [...]` block in DAG.dot -> DPSIR category
DPSIR = {
    "#EF8C1A": "Driver", "#8E24AA": "Pressure", "#00897B": "State",
    "#C62828": "Impact", "#0097A7": "Response",
}
DPSIR_COLORS = {v: k for k, v in DPSIR.items()}
