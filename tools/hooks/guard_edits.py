"""Claude Code PreToolUse hook: block edits CrossTwin never makes by hand.

Wired in .claude/settings.json for Edit|Write|MultiEdit. Reads the hook JSON on
stdin; exit 2 blocks the tool call and shows stderr to Claude.

Blocked:
- writing a migration file (new or whole-file overwrite): schema migrations come
  from `makemigrations`, data steps from `makemigrations <app> --empty -n <name>`
  followed by an Edit that adds only the RunPython (Edit stays allowed);
- `.env` (secrets; `.env_template` is fine);
- `uv.lock` and `requirements.txt` (generated by `uv lock` / `uv export`).
"""
import json
import sys
from pathlib import Path

GENERATED = {
    "uv.lock": "generated: change pyproject.toml and run `uv lock` (or `uv add <pkg>`).",
    "requirements.txt": "generated: run `uv export --format requirements-txt --no-hashes -o requirements.txt`.",
}


def main() -> int:
    try:
        data = json.load(sys.stdin)
    except ValueError:
        return 0
    tool = data.get("tool_name", "")
    path = (data.get("tool_input") or {}).get("file_path") or ""
    if not path:
        return 0
    p = Path(path)
    name = p.name

    if name == ".env":
        print("Blocked: .env holds secrets and local settings. Ask the user to change it, "
              "or edit .env_template for new keys.", file=sys.stderr)
        return 2
    if name in GENERATED:
        print(f"Blocked: {name} is {GENERATED[name]}", file=sys.stderr)
        return 2
    if (tool == "Write" and p.parent.name == "migrations"
            and p.suffix == ".py" and name != "__init__.py"):
        print("Blocked: never write a migration file by hand (CLAUDE.md). Run "
              "`uv run python manage.py makemigrations <app>`; for a data step run "
              "`makemigrations <app> --empty -n <name>` and then Edit in only the RunPython.",
              file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
